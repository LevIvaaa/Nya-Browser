// Turns the certificates in build/roots into src/main/roots.ts.
//
// The PEM files are in the repository so the authority the browser carries can
// be read and checked by anyone; this only rewrites them as a module, and
// records each one's SHA-256 beside it. trust.ts checks that fingerprint when
// it loads, so a swapped PEM stops the browser at startup instead of quietly
// becoming a different authority.
//
//   node build/tools/make-roots.mjs

import { X509Certificate } from 'crypto'
import { readFileSync, writeFileSync } from 'fs'
import { dirname, join } from 'path'
import { fileURLToPath } from 'url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..')

// The order is the order the padlock panel lists them in.
const SOURCES = [
  {
    file: 'russian-trusted-root-ca.crt',
    name: 'Russian Trusted Root CA',
    source: 'https://gu-st.ru/content/lending/russian_trusted_root_ca_pem.crt'
  },
  {
    file: 'russian-trusted-sub-ca.crt',
    name: 'Russian Trusted Sub CA',
    source: 'https://gu-st.ru/content/lending/russian_trusted_sub_ca_pem.crt'
  }
]

// A root the browser carries is trusted only where it has any business being
// trusted. The certificates below exist because Russian sites could no longer
// be issued for by the usual authorities, so that is the whole of their remit:
// a chain reaching one of them opens a .ru address and nothing else.
const SUFFIXES = ['.ru', '.su', '.xn--p1ai']

const NL = '\n'
const lines = [
  '// ---------------------------------------------------------------------------',
  '// Root certificates the browser carries itself.',
  '//',
  '// Generated by build/tools/make-roots.mjs from build/roots — do not edit by',
  '// hand. The PEM files are in the repository so what the browser trusts can be',
  '// read and verified; the fingerprints here are checked against the parsed',
  '// certificates at startup, so a swapped file is a crash rather than a silently',
  '// different authority.',
  '// ---------------------------------------------------------------------------',
  '',
  'export interface BundledRoot {',
  '  /** what to call it where the browser has to name it */',
  '  name: string',
  '  pem: string',
  '  /** SHA-256 of the DER, colon-separated upper case, as openssl prints it */',
  '  fingerprint: string',
  '}',
  '',
  '/**',
  ' * Domains these roots may be used for. Trusting a root normally means trusting',
  ' * it for every name on the internet; these are carried for one purpose, and are',
  ' * held to it. A certificate signed by one of them for a host outside this list',
  ' * is refused exactly as it would have been before it was carried at all.',
  ' */',
  'export const BUNDLED_ROOT_SUFFIXES = [' +
    SUFFIXES.map((s) => JSON.stringify(s)).join(', ') +
    '] as const',
  '',
  'export const BUNDLED_ROOTS: BundledRoot[] = ['
]

for (const entry of SOURCES) {
  const pem = readFileSync(join(root, 'build', 'roots', entry.file), 'utf8').trim().replace(/\r/g, '')
  const parsed = new X509Certificate(pem)
  lines.push('  {')
  lines.push(`    name: ${JSON.stringify(entry.name)},`)
  lines.push(`    // ${entry.source}`)
  lines.push(`    // valid ${parsed.validFrom} .. ${parsed.validTo}`)
  lines.push(`    fingerprint: ${JSON.stringify(parsed.fingerprint256.toUpperCase())},`)
  lines.push('    pem: [')
  for (const line of pem.split(NL)) lines.push(`      ${JSON.stringify(line)},`)
  lines.push("    ].join('\\n')")
  lines.push('  },')
  console.log(`${entry.name}: ${parsed.fingerprint256.slice(0, 23)}… valid to ${parsed.validTo}`)
}

lines.push(']')
lines.push('')

writeFileSync(join(root, 'src', 'main', 'roots.ts'), lines.join(NL))
console.log(`src/main/roots.ts: ${SOURCES.length} certificates, ${SUFFIXES.join(' ')} only`)
